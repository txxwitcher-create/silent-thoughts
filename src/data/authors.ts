export const AUTHOR_MAP: Record<string, AuthorProfile> = Object.fromEntries(
  APPROVED_AUTHORS.map((author) => [author.id, author])
);

export function getAlphabeticalLiteraryAuthors(): AuthorProfile[] {
  return APPROVED_AUTHORS.filter((a) => a.kind === 'literary').sort((a, b) =>
    a.name.localeCompare(b.name, 'en', { sensitivity: 'base' })
  );
}

export function getSpecialReligiousProfiles(): AuthorProfile[] {
  return APPROVED_AUTHORS.filter((a) => a.kind === 'religious_hadith');
}

export function getAuthorById(id: string): AuthorProfile | undefined {
  return AUTHOR_MAP[id];
}
